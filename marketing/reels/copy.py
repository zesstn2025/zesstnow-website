def yt_description(key):
    """The YouTube description with its chapter block resolved.

    The placeholder lives in COPY so the timestamps are never stale, but that
    means every reader has to resolve it. post.py builds the real upload payload
    and was emitting the raw `__CHAPTERS_…__` token straight into the video
    description — caught by reading the rendered plan rather than the code.
    """
    desc = COPY[key]["yt_desc"]
    token = "__CHAPTERS_" + key + "__"
    if token in desc:
        desc = desc.replace(token, chapters(key, LABELS[key]))
    return desc


